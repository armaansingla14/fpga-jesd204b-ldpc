#!/usr/bin/env python3
"""Thermal estimate for every generated build configuration (MODELED).

    python scripts/thermal_report.py [--ta 25 50] [--tj-max 100]

Reads results/build_configs.csv (scripts/gen_configs.py) and writes
results/thermal_model.csv and results/thermal_model.md. These are model
outputs from assumed coefficients (see jesdldpc/thermal.py), not
measurements or vendor estimates.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from jesdldpc import thermal  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ta", type=float, nargs="+", default=[25.0, 50.0])
    ap.add_argument("--tj-max", type=float, default=100.0)
    a = ap.parse_args()
    cfgs = list(csv.DictReader(open(ROOT / "results" / "build_configs.csv")))
    rows = []
    for c in cfgs:
        for ta in a.ta:
            for cool in thermal.COOLING:
                tj, p = thermal.junction_temp(int(c["lanes"]), int(c["num_dec"]),
                                              float(c["clk_mhz"]), ta, cool)
                rows.append({"name": c["name"], "lanes": c["lanes"], "num_dec": c["num_dec"],
                             "clk_mhz": c["clk_mhz"], "ta_c": ta, "cooling": cool.name,
                             "theta_ja": cool.theta_ja, "power_w": round(p["total_w"], 3),
                             "gt_w": round(p["gt_w"], 3), "logic_w": round(p["logic_w"], 3),
                             "static_w": round(p["static_w"], 3), "tj_c": round(tj, 1),
                             "margin_c": round(a.tj_max - tj, 1)})
    out = ROOT / "results"
    with open(out / "thermal_model.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    # summary: worst config per cooling option and ambient
    md = ["# Thermal estimate (MODELED)", "",
          "Generated by `scripts/thermal_report.py` from `results/build_configs.csv`.",
          "Power and thermal-resistance coefficients are assumptions (`jesdldpc/thermal.py`),",
          "not datasheet values or measurements. Power from a real Vivado",
          "`report_power` run would replace the power model.", "",
          f"Tj limit used for the margin column: {a.tj_max:.0f} degC.", "",
          "| Ambient (degC) | Cooling | theta_JA (degC/W) | Configs over limit | "
          "Lowest power config (W -> Tj) | Highest power config (W -> Tj) |",
          "|---:|---|---:|---:|---|---|"]
    for ta in a.ta:
        for cool in thermal.COOLING:
            rs = [r for r in rows if r["ta_c"] == ta and r["cooling"] == cool.name]
            lo = min(rs, key=lambda r: r["power_w"])
            hi = max(rs, key=lambda r: r["power_w"])
            over = sum(r["margin_c"] < 0 for r in rs)
            md.append(f"| {ta:.0f} | {cool.name} | {cool.theta_ja} | {over}/{len(rs)} | "
                      f"{lo['name']}: {lo['power_w']:.2f} W -> {lo['tj_c']:.1f} | "
                      f"{hi['name']}: {hi['power_w']:.2f} W -> {hi['tj_c']:.1f} |")
    (out / "thermal_model.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())

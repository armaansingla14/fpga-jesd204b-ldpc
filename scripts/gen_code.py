#!/usr/bin/env python3
"""Search for the QC-LDPC information-part shifts and emit the RTL include.

    python scripts/gen_code.py --search      # print a girth>=6 candidate
    python scripts/gen_code.py               # write rtl/ldpc/ldpc_code.svh

The mask (which base entries are non-zero) is fixed; shifts are drawn from a
seeded RNG until the lifted graph has no 4-cycles. Among the first 200
valid candidates the one with the best floating-point FER at 2.5 dB on a
small Monte-Carlo run is printed. The chosen matrix is stored in
jesdldpc/ldpc.py (BASE_INFO) so that the model, the RTL and the docs use one
definition.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from jesdldpc import ldpc  # noqa: E402

MASK = np.array([[1, 1, 1, 0], [1, 0, 1, 1], [0, 1, 1, 1], [1, 1, 0, 0]])


def full_base(info: np.ndarray) -> np.ndarray:
    b = -np.ones((ldpc.MB, ldpc.NB), dtype=int)
    b[:, :ldpc.KB] = info
    for i in range(ldpc.MB):
        b[i, ldpc.KB + i] = 0
        if i > 0:
            b[i, ldpc.KB + i - 1] = 0
    return b


def quick_fer(base: np.ndarray, ebn0: float, frames: int, seed: int) -> float:
    saved = ldpc.BASE, ldpc.EDGES
    ldpc.BASE = base
    ldpc.EDGES = [(r, c, int(base[r, c])) for r in range(ldpc.MB) for c in range(ldpc.NB)
                  if base[r, c] >= 0]
    rng = np.random.default_rng(seed)
    msg = rng.integers(0, 2, size=(frames, ldpc.K), dtype=np.uint8)
    cw = ldpc.encode(msg)
    hard, _, _ = ldpc.decode_float(ldpc.awgn_llr(cw, ebn0, rng), max_iter=10)
    fer = float(np.mean(np.any(hard != cw, axis=1)))
    ldpc.BASE, ldpc.EDGES = saved
    return fer


def search(n_valid: int = 200, seed: int = 2024) -> np.ndarray:
    rng = np.random.default_rng(seed)
    best, best_fer, found = None, 2.0, 0
    while found < n_valid:
        info = np.where(MASK == 1, rng.integers(0, ldpc.Z, size=MASK.shape), -1)
        base = full_base(info)
        if not ldpc.girth_ok(base):
            continue
        found += 1
        fer = quick_fer(base, 2.5, 400, seed=7)
        if fer < best_fer:
            best, best_fer = info, fer
    print(f"best of {n_valid} girth>=6 candidates: FER@2.5dB={best_fer:.4f}")
    print(repr(best))
    return best


def write_svh(path: Path) -> None:
    e = ldpc.EDGES
    rows = [r for r, _, _ in e]
    lines = [
        "// ldpc_code.svh - generated by scripts/gen_code.py from jesdldpc/ldpc.py",
        f"// Rate-1/2 QC-LDPC, base {ldpc.MB}x{ldpc.NB}, Z={ldpc.Z}, {len(e)} non-zero blocks.",
        f"localparam int Z = {ldpc.Z};",
        f"localparam int MB = {ldpc.MB};",
        f"localparam int NB = {ldpc.NB};",
        f"localparam int KB = {ldpc.KB};",
        f"localparam int NE = {len(e)};",
        f"localparam int MAXDEG = {max(rows.count(r) for r in range(ldpc.MB))};",
    ]

    def table_fn(name: str, values: list[int]) -> list[str]:
        # case-based lookup functions: portable across simulators (unpacked
        # localparam arrays were not reliably evaluated in Verilator 5.020)
        out = [f"function automatic int {name}(input int i);", "  case (i)"]
        out += [f"    {i}: return {v};" for i, v in enumerate(values)]
        out += ["    default: return -1;", "  endcase", "endfunction"]
        return out

    lines += table_fn("E_COL", [c for _, c, _ in e])
    lines += table_fn("E_SHIFT", [s for _, _, s in e])
    lines += table_fn("ROW_START", [rows.index(r) for r in range(ldpc.MB)])
    lines += table_fn("ROW_DEG", [rows.count(r) for r in range(ldpc.MB)])
    lines += table_fn("BASE_INFO", [int(v) for v in ldpc.BASE_INFO.flatten()])
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--search", action="store_true")
    a = ap.parse_args()
    if a.search:
        search()
        return 0
    assert ldpc.girth_ok(ldpc.BASE), "BASE has 4-cycles"
    write_svh(ROOT / "rtl" / "ldpc" / "ldpc_code.svh")
    return 0


if __name__ == "__main__":
    sys.exit(main())

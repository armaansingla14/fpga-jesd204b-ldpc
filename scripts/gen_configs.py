#!/usr/bin/env python3
"""Build-configuration sweep generator for the Vivado non-project flow.

Expands the parameter grid below into one TCL config file per build
(build/configs/<name>.tcl) plus build/configs/sweep.txt (the list consumed by
vivado/run_sweep.tcl / vivado/run_sweep.sh) and results/build_configs.csv.

    python scripts/gen_configs.py            # 72 configurations
    python scripts/gen_configs.py --lint     # also elaborate every distinct
                                             # RTL parameter set with Verilator

Vivado is not available here, so the generated builds were NOT run; --lint
only proves that each parameter combination elaborates.
"""
from __future__ import annotations

import argparse
import csv
import itertools
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "configs"

GRID = {
    "lanes":    [1, 2, 4, 8],
    "num_dec":  [1, 2, 4],               # LDPC decoder cores ("LDPC parallelism")
    "clk_mhz":  [122.88, 153.6, 245.76], # character clock; line rate = 10 x clk
    "scr":      [0, 1],
}
FIXED = {"F": 2, "K": 16, "MAX_ITER": 10, "part": "xczu9eg-ffvb1156-2-e"}

RTL = ["rtl/jesd/jesd_pkg.sv", "rtl/jesd/enc_8b10b.sv", "rtl/jesd/dec_8b10b.sv",
       "rtl/jesd/comma_align.sv", "rtl/jesd/jesd_tx.sv", "rtl/jesd/jesd_rx.sv",
       "rtl/ldpc/ldpc_encoder.sv", "rtl/ldpc/ldpc_decoder.sv", "rtl/ldpc/ldpc_dec_array.sv",
       "rtl/top/fpga_top.sv"]


def configs() -> list[dict]:
    out = []
    for lanes, nd, clk, scr in itertools.product(*GRID.values()):
        name = f"L{lanes}_D{nd}_C{int(round(clk))}_S{scr}"
        out.append({"name": name, "lanes": lanes, "num_dec": nd, "clk_mhz": clk, "scr": scr,
                    "line_rate_gbps": round(clk * 10 / 1000, 4), **FIXED})
    return out


def write_tcl(c: dict) -> None:
    period = 1000.0 / c["clk_mhz"]
    (OUT / f"{c['name']}.tcl").write_text(f"""# generated by scripts/gen_configs.py
set CFG(name)     {c['name']}
set CFG(part)     {c['part']}
set CFG(L)        {c['lanes']}
set CFG(NUM_DEC)  {c['num_dec']}
set CFG(SCR)      {c['scr']}
set CFG(F)        {c['F']}
set CFG(K)        {c['K']}
set CFG(MAX_ITER) {c['MAX_ITER']}
set CFG(clk_mhz)  {c['clk_mhz']}
set CFG(period)   {period:.4f}
""")


def lint(cfgs: list[dict]) -> int:
    combos = sorted({(c["lanes"], c["num_dec"], c["scr"]) for c in cfgs})
    lines = ["set -e"]
    for L, nd, scr in combos:
        lines.append(f"verilator --lint-only -Wno-fatal -Wno-WIDTHTRUNC -Wno-WIDTHEXPAND -Irtl/ldpc "
                     f"-GL={L} -GNUM_DEC={nd} -GSCR={scr} --top-module fpga_top {' '.join(RTL)} "
                     f"&& echo LINT_OK L={L} NUM_DEC={nd} SCR={scr}")
    script = ROOT / "build" / "lint_configs.sh"
    script.write_text("\n".join(lines) + "\n")
    p = subprocess.run([str(ROOT / "scripts" / "docker_run.sh"), "bash", "build/lint_configs.sh"],
                       cwd=ROOT, capture_output=True, text=True)
    ok = p.stdout.count("LINT_OK")
    print(p.stdout[-2000:], p.stderr[-2000:])
    print(f"Verilator elaborated {ok}/{len(combos)} distinct RTL parameter sets")
    return ok


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lint", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    cfgs = configs()
    for c in cfgs:
        write_tcl(c)
    (OUT / "sweep.txt").write_text("\n".join(c["name"] for c in cfgs) + "\n")
    res = ROOT / "results"
    res.mkdir(exist_ok=True)
    with open(res / "build_configs.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(cfgs[0].keys()))
        w.writeheader()
        w.writerows(cfgs)
    print(f"generated {len(cfgs)} configurations in {OUT.relative_to(ROOT)}")
    if a.lint:
        n = lint(cfgs)
        (res / "config_lint.txt").write_text(
            f"{len(cfgs)} build configurations generated; "
            f"{n} distinct RTL parameter sets (lanes x decoder cores x scrambling) "
            f"elaborated with Verilator --lint-only.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
